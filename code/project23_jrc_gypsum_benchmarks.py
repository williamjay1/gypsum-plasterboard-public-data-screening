from pathlib import Path
import pandas as pd

WORK = Path(__file__).resolve().parents[1]
out = pd.DataFrame([
    {
        "scenario": "JRC maximum recycling potential",
        "material": "gypsum",
        "recycling_potential_rate": 0.95,
        "baseline_recycling_rate": 0.10,
        "management_route": "recycling to plasterboard",
        "marginal_cost_eur_per_kg_co2e": 0.30,
        "total_ghg_reduction_mt_co2e": 0.20,
        "total_cost_m_eur": 48.0,
        "landfill_tax_eur_per_t_inert": 19.0,
        "source_locator": "JRC135470 Table 14, Table 15, pp. 61-67",
        "source_url": "https://publications.jrc.ec.europa.eu/repository/handle/JRC135470",
        "status": "external stylised EU benchmark; not this study result",
        "limitation": "Uses literature/stakeholder assumptions and average values; not contamination-stratified and not a current market price series",
    }
])
out.to_csv(WORK / "results" / "jrc_gypsum_cost_climate_benchmark.csv", index=False)

qa = pd.DataFrame([
    {"check": "reported rates ordered", "pass": bool(out.loc[0, "baseline_recycling_rate"] <= out.loc[0, "recycling_potential_rate"])},
    {"check": "reported cost and GHG positive", "pass": bool((out.loc[0, ["total_ghg_reduction_mt_co2e", "total_cost_m_eur"]] > 0).all())},
    {"check": "implied rounded average cost per t CO2e", "value_eur_per_t_co2e": float(out.loc[0, "total_cost_m_eur"] / out.loc[0, "total_ghg_reduction_mt_co2e"]), "pass": True},
])
qa.to_csv(WORK / "results" / "jrc_gypsum_cost_climate_benchmark_validation.csv", index=False)
(WORK / "results" / "jrc_gypsum_cost_climate_benchmark_README.txt").write_text(
    "Values are transcribed from the JRC 2024 report, Table 14 and Table 15.\n"
    "They are external stylised EU benchmarks used to bound interpretation and construct scenario context.\n"
    "They are not estimates generated by the present public-data screening model, nor a gypsum-specific price series.\n"
    "The report itself notes that average values are not representative of every Member State and that financial constraints are not considered in the maximum-potential scenario.\n",
    encoding="utf-8",
)
print(out.to_string(index=False))
print(qa.to_string(index=False))
